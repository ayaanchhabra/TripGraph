-- schema/01_tables.sql   (K)
-- Creates every table with primary keys and defaults.
-- Foreign keys, CHECK and UNIQUE rules are in 02_constraints.sql.
-- Run order: 01 -> 02 -> 03, then data/load_all.sql
--   psql -U postgres -d tripgraph -f schema/01_tables.sql
--
-- WARNING: this drops and recreates all tables (handy for re-running during development).

\set ON_ERROR_STOP on

DROP TABLE IF EXISTS audit_log, trip_leg, trip, review, place_tag, opening_hours,
                     food_outlet, place, tag, edge, node, category, app_user CASCADE;

-- Ids use IDENTITY "BY DEFAULT" so A's loaders can insert explicit ids
-- (node_id, edge_id, place_id) and A's setval() lines still work.

CREATE TABLE app_user (
  user_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT        NOT NULL,
  email      TEXT        NOT NULL,
  role       TEXT        NOT NULL DEFAULT 'student',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE category (
  category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  group_name  TEXT NOT NULL            -- e.g. 'Food and drink', 'Essentials'
);

-- The map: a node is a landmark/stop (gate, metro, bus stop, e-rickshaw stand, a shop cluster)
CREATE TABLE node (
  node_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    TEXT NOT NULL,
  kind    TEXT NOT NULL
);

-- An edge is ONE direction of travel. Two-way roads need two rows (A->B and B->A).
CREATE TABLE edge (
  edge_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_node  INT           NOT NULL,
  to_node    INT           NOT NULL,
  mode       TEXT          NOT NULL,
  distance_m INT           NOT NULL,
  time_min   INT           NOT NULL,
  fare       NUMERIC(6,2)  NOT NULL DEFAULT 0
);

CREATE TABLE place (
  place_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             TEXT          NOT NULL,
  category_id      INT           NOT NULL,
  address          TEXT,
  lat              NUMERIC(9,6)  NOT NULL,
  lon              NUMERIC(9,6)  NOT NULL,
  price_level      SMALLINT      NOT NULL,
  student_discount BOOLEAN       NOT NULL DEFAULT false,
  avg_rating       NUMERIC(3,2)  NOT NULL DEFAULT 0,   -- denormalized, kept up to date by a trigger
  review_count     INT           NOT NULL DEFAULT 0,   -- denormalized, kept up to date by a trigger
  node_id          INT           NOT NULL              -- the map node this place is reached from
);

-- Specialization of place (only Food and drink places have a row here)
CREATE TABLE food_outlet (
  place_id INT     PRIMARY KEY,
  cuisine  TEXT,
  is_veg   BOOLEAN NOT NULL
);

CREATE TABLE tag (
  tag_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   TEXT NOT NULL
);

CREATE TABLE place_tag (
  place_id INT NOT NULL,
  tag_id   INT NOT NULL,
  PRIMARY KEY (place_id, tag_id)
);

-- Weak entity: identified by (place_id, day). day is ISO: 1 = Monday ... 7 = Sunday.
-- If close_time < open_time the place closes after midnight (next day).
CREATE TABLE opening_hours (
  place_id   INT      NOT NULL,
  day        SMALLINT NOT NULL,
  open_time  TIME     NOT NULL,
  close_time TIME     NOT NULL,
  PRIMARY KEY (place_id, day)
);

CREATE TABLE review (
  user_id     INT         NOT NULL,
  place_id    INT         NOT NULL,
  rating      SMALLINT    NOT NULL,
  review_text TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, place_id)            -- one review per user per place
);

CREATE TABLE trip (
  trip_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT         NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Weak entity: the ordered legs of a trip
CREATE TABLE trip_leg (
  trip_id INT      NOT NULL,
  leg_no  SMALLINT NOT NULL,
  edge_id INT      NOT NULL,
  PRIMARY KEY (trip_id, leg_no)
);

-- Optional: written to by triggers
CREATE TABLE audit_log (
  log_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action     TEXT        NOT NULL,
  table_name TEXT        NOT NULL,
  record_id  TEXT,
  logged_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
