-- normalization/normalized_tables.sql
-- Purpose : The FINAL normalized design (BCNF, plus the design steps explained in
--           decomposition_steps.md), built in its own schema norm_demo so it cannot
--           clash with the real TripGraph tables. The tables are filled from
--           tripgraph_messy to prove that no information is lost.
-- Needs   : normalization/messy_table.sql must have been run first (it creates the table
--           tripgraph_messy). The real schema is NOT needed, except for the optional
--           comparison in section 6 (it only reports differences, it never fails).
-- Run     : psql -U postgres -d tripgraph -v ON_ERROR_STOP=1 -f normalization/messy_table.sql
--           psql -U postgres -d tripgraph -v ON_ERROR_STOP=1 -f normalization/normalized_tables.sql
-- Re-run  : safe. The schema norm_demo is dropped and rebuilt every time.

DROP SCHEMA IF EXISTS norm_demo CASCADE;
CREATE SCHEMA norm_demo;

-- ---------------------------------------------------------------------------
-- 1. The tables (column names match the real tables on purpose)
-- ---------------------------------------------------------------------------

-- C -> category_name, group_name. The group depends on the category, so it lives here once.
CREATE TABLE norm_demo.category (
  category_id INT  PRIMARY KEY,
  name        TEXT NOT NULL UNIQUE,      -- second candidate key (name -> category_id)
  group_name  TEXT NOT NULL
);

-- A map node. The same table serves two roles: the node a place is reached from, and the
-- node an edge leads to. (In the FD work these were two attribute sets, N and TO.)
CREATE TABLE norm_demo.node (
  node_id INT  PRIMARY KEY,
  name    TEXT NOT NULL UNIQUE,
  kind    TEXT NOT NULL
);

-- place_id -> everything about the place itself. No category name, no node name.
CREATE TABLE norm_demo.place (
  place_id         INT      PRIMARY KEY,
  name             TEXT     NOT NULL,
  category_id      INT      NOT NULL REFERENCES norm_demo.category(category_id),
  address          TEXT,
  price_level      SMALLINT NOT NULL CHECK (price_level BETWEEN 1 AND 3),
  student_discount BOOLEAN  NOT NULL,
  node_id          INT      NOT NULL REFERENCES norm_demo.node(node_id)
);

-- Design step (not forced by BCNF): cuisine and is_veg only make sense for food places,
-- so they get their own table instead of NULLs in every non-food row.
CREATE TABLE norm_demo.food_outlet (
  place_id INT     PRIMARY KEY REFERENCES norm_demo.place(place_id) ON DELETE CASCADE,
  cuisine  TEXT,
  is_veg   BOOLEAN NOT NULL
);

-- The tag list (repeating group) becomes a many-to-many pair of tables.
CREATE TABLE norm_demo.tag (
  tag_id INT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name   TEXT NOT NULL UNIQUE
);

CREATE TABLE norm_demo.place_tag (
  place_id INT NOT NULL REFERENCES norm_demo.place(place_id) ON DELETE CASCADE,
  tag_id   INT NOT NULL REFERENCES norm_demo.tag(tag_id)     ON DELETE CASCADE,
  PRIMARY KEY (place_id, tag_id)
);

-- (place_id, day) -> open_time, close_time
CREATE TABLE norm_demo.opening_hours (
  place_id   INT      NOT NULL REFERENCES norm_demo.place(place_id) ON DELETE CASCADE,
  day        SMALLINT NOT NULL CHECK (day BETWEEN 1 AND 7),
  open_time  TIME     NOT NULL,
  close_time TIME     NOT NULL,
  PRIMARY KEY (place_id, day)
);

-- user_id -> name, email (and email -> user_id)
CREATE TABLE norm_demo.app_user (
  user_id INT  PRIMARY KEY,
  name    TEXT NOT NULL,
  email   TEXT NOT NULL UNIQUE
);

-- (user_id, place_id) -> rating
CREATE TABLE norm_demo.review (
  user_id  INT      NOT NULL REFERENCES norm_demo.app_user(user_id) ON DELETE CASCADE,
  place_id INT      NOT NULL REFERENCES norm_demo.place(place_id)   ON DELETE CASCADE,
  rating   SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  PRIMARY KEY (user_id, place_id)
);

-- edge_id -> from_node, to_node, mode, distance, time, fare
CREATE TABLE norm_demo.edge (
  edge_id    INT          PRIMARY KEY,
  from_node  INT          NOT NULL REFERENCES norm_demo.node(node_id),
  to_node    INT          NOT NULL REFERENCES norm_demo.node(node_id),
  mode       TEXT         NOT NULL CHECK (mode IN ('walk', 'erickshaw', 'auto', 'metro', 'bus')),
  distance_m INT          NOT NULL CHECK (distance_m > 0),
  time_min   INT          NOT NULL CHECK (time_min >= 0),
  fare       NUMERIC(6,2) NOT NULL CHECK (fare >= 0),
  CHECK (from_node <> to_node)
);

-- ---------------------------------------------------------------------------
-- 2. Step 1 (1NF) as a view: split the tags list into one row per tag
-- ---------------------------------------------------------------------------
CREATE VIEW norm_demo.messy_1nf AS
SELECT m.place_id, m.place_name, m.category_id, m.category_name, m.group_name, m.address,
       m.price_level, m.student_discount, m.node_id, m.node_name, m.node_kind,
       m.cuisine, m.is_veg, t.tag_name,
       m.day, m.open_time, m.close_time,
       m.user_id, m.user_name, m.user_email, m.rating,
       m.edge_id, m.mode, m.distance_m, m.time_min, m.fare,
       m.to_node_id, m.to_node_name, m.to_node_kind
FROM public.tripgraph_messy m
CROSS JOIN LATERAL regexp_split_to_table(m.tags, ',\s*') AS t(tag_name);

-- ---------------------------------------------------------------------------
-- 3. Fill the tables. Every fact is stored ONCE (SELECT DISTINCT removes the copies).
--    Order matters because of the foreign keys.
-- ---------------------------------------------------------------------------
INSERT INTO norm_demo.category (category_id, name, group_name)
SELECT DISTINCT category_id, category_name, group_name FROM public.tripgraph_messy;

-- UNION (not UNION ALL) because a node can appear as a place node and as an edge target.
INSERT INTO norm_demo.node (node_id, name, kind)
SELECT node_id, node_name, node_kind FROM public.tripgraph_messy
UNION
SELECT to_node_id, to_node_name, to_node_kind FROM public.tripgraph_messy;

INSERT INTO norm_demo.place (place_id, name, category_id, address, price_level, student_discount, node_id)
SELECT DISTINCT place_id, place_name, category_id, address, price_level, student_discount, node_id
FROM public.tripgraph_messy;

INSERT INTO norm_demo.food_outlet (place_id, cuisine, is_veg)
SELECT DISTINCT place_id, cuisine, is_veg
FROM public.tripgraph_messy
WHERE is_veg IS NOT NULL;

INSERT INTO norm_demo.tag (name)
SELECT DISTINCT tag_name FROM norm_demo.messy_1nf ORDER BY tag_name;

INSERT INTO norm_demo.place_tag (place_id, tag_id)
SELECT DISTINCT v.place_id, g.tag_id
FROM norm_demo.messy_1nf v
JOIN norm_demo.tag g ON g.name = v.tag_name;

INSERT INTO norm_demo.opening_hours (place_id, day, open_time, close_time)
SELECT DISTINCT place_id, day, open_time, close_time FROM public.tripgraph_messy;

INSERT INTO norm_demo.app_user (user_id, name, email)
SELECT DISTINCT user_id, user_name, user_email FROM public.tripgraph_messy;

INSERT INTO norm_demo.review (user_id, place_id, rating)
SELECT DISTINCT user_id, place_id, rating FROM public.tripgraph_messy;

-- from_node of an edge is the node the place is reached from (node_id in the messy table)
INSERT INTO norm_demo.edge (edge_id, from_node, to_node, mode, distance_m, time_min, fare)
SELECT DISTINCT edge_id, node_id, to_node_id, mode, distance_m, time_min, fare
FROM public.tripgraph_messy;

-- ---------------------------------------------------------------------------
-- 4. Redundancy gone: how many times is each fact stored now?
-- ---------------------------------------------------------------------------
\echo
\echo === Rows per table (the messy table needed 12 rows, 36 after splitting tags) ===
SELECT 'category' AS table_name, count(*) AS row_count FROM norm_demo.category
UNION ALL SELECT 'node',          count(*) FROM norm_demo.node
UNION ALL SELECT 'place',         count(*) FROM norm_demo.place
UNION ALL SELECT 'food_outlet',   count(*) FROM norm_demo.food_outlet
UNION ALL SELECT 'tag',           count(*) FROM norm_demo.tag
UNION ALL SELECT 'place_tag',     count(*) FROM norm_demo.place_tag
UNION ALL SELECT 'opening_hours', count(*) FROM norm_demo.opening_hours
UNION ALL SELECT 'app_user',      count(*) FROM norm_demo.app_user
UNION ALL SELECT 'review',        count(*) FROM norm_demo.review
UNION ALL SELECT 'edge',          count(*) FROM norm_demo.edge;

\echo
\echo === The update anomaly is gone: one address change touches exactly one row ===
BEGIN;
UPDATE norm_demo.place SET address = 'Sector 3 market, Dwarka (next to the gate)' WHERE place_id = 3;
SELECT place_id, address FROM norm_demo.place WHERE place_id = 3;   -- one row, one address
ROLLBACK;

\echo
\echo === The delete anomaly is gone: deleting the only review keeps the place and its category ===
BEGIN;
DELETE FROM norm_demo.review WHERE place_id = 6;
SELECT p.place_id, p.name, c.name AS category
FROM norm_demo.place p JOIN norm_demo.category c USING (category_id)
WHERE p.place_id = 6;                                               -- still there
ROLLBACK;

\echo
\echo === The insert anomaly is gone: a new category and a new place need no review ===
BEGIN;
INSERT INTO norm_demo.category (category_id, name, group_name) VALUES (12, 'Laundry and ironing', 'Essentials');
INSERT INTO norm_demo.place (place_id, name, category_id, address, price_level, student_discount, node_id)
VALUES (13, 'Sample Laundry', 12, 'Sector 3, Dwarka', 1, false, 8);
SELECT place_id, name FROM norm_demo.place WHERE place_id = 13;     -- stored, with zero reviews
ROLLBACK;

-- ---------------------------------------------------------------------------
-- 5. Lossless-join checks
-- ---------------------------------------------------------------------------

-- 5a. BCNF stage (strict proof on data). After the BCNF split one small table is left over:
--     the key of the original table (place, tag, day, edge, user). Joined with the tables
--     above it rebuilds the 1NF table EXACTLY. Both EXCEPT counts must be 0.
CREATE TEMP TABLE bcnf_link AS
SELECT DISTINCT place_id, tag_name, day, edge_id, user_id FROM norm_demo.messy_1nf;

CREATE TEMP VIEW rebuilt_from_link AS
SELECT p.place_id, p.name AS place_name, c.category_id, c.name AS category_name, c.group_name,
       p.address, p.price_level, p.student_discount, p.node_id, n.name AS node_name, n.kind AS node_kind,
       f.cuisine, f.is_veg, l.tag_name,
       h.day, h.open_time, h.close_time,
       u.user_id, u.name AS user_name, u.email AS user_email, r.rating,
       e.edge_id, e.mode, e.distance_m, e.time_min, e.fare,
       e.to_node AS to_node_id, tn.name AS to_node_name, tn.kind AS to_node_kind
FROM bcnf_link l
JOIN norm_demo.place         p  ON p.place_id = l.place_id
JOIN norm_demo.category      c  ON c.category_id = p.category_id
JOIN norm_demo.node          n  ON n.node_id = p.node_id
LEFT JOIN norm_demo.food_outlet f ON f.place_id = p.place_id
JOIN norm_demo.opening_hours h  ON h.place_id = l.place_id AND h.day = l.day
JOIN norm_demo.review        r  ON r.place_id = l.place_id AND r.user_id = l.user_id
JOIN norm_demo.app_user      u  ON u.user_id = l.user_id
JOIN norm_demo.edge          e  ON e.edge_id = l.edge_id
JOIN norm_demo.node          tn ON tn.node_id = e.to_node;

\echo
\echo === Lossless check (BCNF stage): both numbers must be 0 ===
SELECT count(*) AS in_original_but_not_rebuilt
FROM (SELECT * FROM norm_demo.messy_1nf EXCEPT SELECT * FROM rebuilt_from_link) x;
SELECT count(*) AS in_rebuilt_but_not_original
FROM (SELECT * FROM rebuilt_from_link EXCEPT SELECT * FROM norm_demo.messy_1nf) x;

-- 5b. Final design (4NF step). The leftover table above only records which tag, day,
--     review and edge happened to be listed together in a careless export. Those
--     combinations are not facts, so the final design drops it. Rebuilding from the
--     final tables alone gives every original row back, PLUS the combinations the 12-row
--     sample did not list. Nothing is lost: the first number must be 0.
CREATE TEMP VIEW rebuilt_final AS
SELECT p.place_id, p.name AS place_name, c.category_id, c.name AS category_name, c.group_name,
       p.address, p.price_level, p.student_discount, p.node_id, n.name AS node_name, n.kind AS node_kind,
       f.cuisine, f.is_veg, g.name AS tag_name,
       h.day, h.open_time, h.close_time,
       u.user_id, u.name AS user_name, u.email AS user_email, r.rating,
       e.edge_id, e.mode, e.distance_m, e.time_min, e.fare,
       e.to_node AS to_node_id, tn.name AS to_node_name, tn.kind AS to_node_kind
FROM norm_demo.place p
JOIN norm_demo.category      c  ON c.category_id = p.category_id
JOIN norm_demo.node          n  ON n.node_id = p.node_id
LEFT JOIN norm_demo.food_outlet f ON f.place_id = p.place_id
JOIN norm_demo.place_tag     pt ON pt.place_id = p.place_id
JOIN norm_demo.tag           g  ON g.tag_id = pt.tag_id
JOIN norm_demo.opening_hours h  ON h.place_id = p.place_id
JOIN norm_demo.review        r  ON r.place_id = p.place_id
JOIN norm_demo.app_user      u  ON u.user_id = r.user_id
JOIN norm_demo.edge          e  ON e.from_node = p.node_id
JOIN norm_demo.node          tn ON tn.node_id = e.to_node;

\echo
\echo === Final design: original rows missing after the join (must be 0) ===
SELECT count(*) AS in_original_but_not_rebuilt
FROM (SELECT * FROM norm_demo.messy_1nf EXCEPT SELECT * FROM rebuilt_final) x;

\echo === Rows: original (1NF) vs rebuilt from the final tables (rebuilt is larger: unlisted combinations) ===
SELECT (SELECT count(*) FROM norm_demo.messy_1nf) AS original_rows_1nf,
       (SELECT count(*) FROM rebuilt_final)       AS rebuilt_rows;

-- ---------------------------------------------------------------------------
-- 6. Mapping to the real TripGraph tables (schema/01_tables.sql, 04_favorites.sql)
-- ---------------------------------------------------------------------------
--   norm_demo table   real table        what the real table adds
--   ---------------   ---------------   -------------------------------------------------
--   category          category          nothing
--   node              node              nothing
--   place             place             lat, lon; avg_rating and review_count (see below)
--   food_outlet       food_outlet       nothing
--   tag               tag               nothing
--   place_tag         place_tag         nothing
--   opening_hours     opening_hours     nothing
--   app_user          app_user          role, created_at
--   review            review            review_text, created_at
--   edge              edge              nothing
--
--   Not part of the normalization demo, but in the real design:
--   * trip, trip_leg, favorite, audit_log: not needed to explain the FDs.
--   * place.avg_rating and place.review_count: derived from review, kept on purpose
--     (denormalization, maintained by a trigger). No FD is violated by them, so the
--     normal forms do not object; the cost is the trigger that keeps them correct.
--
-- The two queries below compare column names with the real tables. They only report;
-- they never fail. If the real schema is not loaded, both return no rows.

\echo
\echo === Columns in norm_demo that the real table lacks (expect no rows) ===
SELECT table_name, column_name
FROM information_schema.columns
WHERE table_schema = 'norm_demo' AND table_name IN (
      SELECT table_name FROM information_schema.tables WHERE table_schema = 'public')
EXCEPT
SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public'
ORDER BY 1, 2;

\echo === Columns the real table has beyond norm_demo (expect lat, lon, avg_rating, role, ...) ===
SELECT table_name, column_name
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name IN (
      SELECT table_name FROM information_schema.tables WHERE table_schema = 'norm_demo')
  AND table_name <> 'messy_1nf'
EXCEPT
SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'norm_demo'
ORDER BY 1, 2;
